"""forecast: выручка оператора от пакета eSIM для Турции за 12 месяцев с запуска пилота (с 2027-05-01).
Один знаменатель во всех сценариях и в плане проверки: поездки абонентов оператора в Турцию
(= поездки в Турцию × доля абонентов оператора). Сценарии — допущения (hypothesis), не факт.
Запуск: python tools/analyze.py calc C-165"""
TRIPS = 609_517 + 1_956_084 + 2_741_936 + 1_309_052  # поездок в Турцию за 2025 год [C-160] [C-161] [C-134] [C-162]
PRICE = 518            # ₽ за пакет 5 ГБ на 30 дней, «как у МТС» [C-115]
SUBS = 0.25            # hypothesis [C-164]: доля абонентов оператора среди поездок в Турцию
BUY = {"низкий": 0.005, "базовый": 0.01, "высокий": 0.03}     # hypothesis [C-166]: доля поездок абонентов с покупкой
REFUND = {"низкий": 0.10, "базовый": 0.05, "высокий": 0.03}   # hypothesis [C-158]: доля возвратов «не заработало»
base = TRIPS * SUBS
print(f"Поездок абонентов в Турцию (знаменатель): {base:,.0f} в год".replace(",", " "))
for s in BUY:
    n = base * BUY[s]; net = n * PRICE * (1 - REFUND[s])
    print(f"{s}: пакетов {n:,.0f}; выручка после возвратов {net/1e6:.1f} млн ₽ в год".replace(",", " "))
for d in (0.15, 0.35):  # чувствительность к доле абонентов, базовый сценарий
    print(f"базовый при доле абонентов {d:.0%}: {TRIPS*d*BUY['базовый']*PRICE*(1-REFUND['базовый'])/1e6:.1f} млн ₽ в год")
print(f"RESULT={base * BUY['базовый'] * PRICE * (1 - REFUND['базовый']) / 1e6:.1f} млн ₽ в год")
