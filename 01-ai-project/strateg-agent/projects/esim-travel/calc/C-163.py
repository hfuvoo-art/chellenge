"""estimate: ёмкость рынка пакета eSIM для Турции за год, если пакет покупают в каждой поездке (верхняя граница, доля = 100 %).
Только факты: поездки в Турцию за 2025 год (S-001, сумма 4 кварталов) × цена пакета 5 ГБ на 30 дней МТС.
Запуск: python tools/analyze.py calc C-163"""
Q = {
    "2025-Q1": 609_517,    # [C-160] Данные!K139
    "2025-Q2": 1_956_084,  # [C-161] Данные!L139
    "2025-Q3": 2_741_936,  # [C-134] Данные!M139
    "2025-Q4": 1_309_052,  # [C-162] Данные!N139
}
PRICE = 518  # ₽ за пакет 5 ГБ на 30 дней [C-115]
trips = sum(Q.values())
cap = trips * PRICE
print(f"Поездок в Турцию за 2025 год: {trips:,} поездок".replace(",", " "))
print(f"Ёмкость при покупке в каждой поездке: {cap/1e6:.1f} млн ₽ в год")
print(f"RESULT={cap/1e6:.1f} млн ₽ в год")
