"""estimate: сколько групп нужно для пилота и сколько месяцев займёт набор.
Единица — семейная группа (одна группа — один вариант обслуживания), событие — первый низкий остаток доли участника.
Допущения — hypothesis, не факт. Запуск: python tools/analyze.py calc C-046"""
from math import sqrt, ceil
P0, P1 = 0.12, 0.09          # доля ограничений за 7 дней: база и наименьшее важное улучшение [C-039], [C-012]
ZA, ZB = 1.96, 0.8416        # двусторонний уровень 5 %, мощность 80 %
CONNECTED = 6_800            # подключённых групп в начале 2-го квартала: 6 500 на начало года [C-005] + рост (допущение)
SUITABLE = 0.5               # доля подходящих групп [C-037]
FIRST_EVENT = 0.2            # доля подходящих групп с первым событием за месяц [C-038]
pbar = (P0 + P1) / 2
n = ceil((ZA * sqrt(2 * pbar * (1 - pbar)) + ZB * sqrt(P0 * (1 - P0) + P1 * (1 - P1))) ** 2 / (P0 - P1) ** 2)
flow = CONNECTED * SUITABLE * FIRST_EVENT
months = 2 * n / flow
n6 = flow * 1.5 / 2           # групп на вариант за 6 недель набора
mde = (ZA + ZB) * sqrt(2 * P0 * (1 - P0) / n6)
print(f"Нужно групп на вариант: {n}; всего {2*n}")
print(f"Поток впервые подходящих групп: {flow:.0f} в месяц")
print(f"За 6 недель набора: {n6:.0f} групп на вариант, различимое снижение {mde*100:.1f} п.п. (с 12 % до {(P0-mde)*100:.1f} %)")
for f in (0.1, 0.3):
    print(f"при доле событий {f:.0%}: набор {2*n/(CONNECTED*SUITABLE*f):.1f} мес.")
print(f"RESULT={months:.1f} мес.")
