const STOP = new Set(["что", "как", "мне", "меня", "это", "если", "или", "для", "когда", "можно", "нужно", "надо", "есть", "был", "была", "по", "на", "не", "и", "в", "с", "а", "я", "у", "ли", "про", "долго"]);

// Ключ с «~» в начале — общее слово: по одному такому слову пункт не выбираем
// («какие оценки у…» ещё не вопрос про шкалу оценок).
const MIN_SCORE = 2;

function tokens(text: string): string[] {
  return text.toLowerCase().replace(/ё/g, "е").split(/[^a-zа-я0-9]+/).filter((w) => w.length > 2 && !STOP.has(w));
}

/** Слово совпало с ключом: слово начинается с ключа или (для длинных слов) ключ начинается с первых 6 букв слова. */
function hit(word: string, key: string): boolean {
  return word.startsWith(key) || (word.length >= 6 && key.length >= 6 && key.startsWith(word.slice(0, 6)));
}

/** Поиск по ключам с весами. Возвращает до 3 пунктов; если уверенного совпадения нет, возвращает пустой список,
 *  и помощник честно отвечает «не нашёл», а не подставляет первый попавшийся пункт. */
export function searchArticles(query: string): Article[] {
  const q = query.toLowerCase().replace(/ё/g, "е");
  const words = tokens(query);
  const scored = ARTICLES.map((a) => {
    let score = 0;
    if (a.needs && !a.needs.some((n) => words.some((w) => w.startsWith(n)))) return { a, score };
    for (const raw of a.keywords) {
      const weak = raw.startsWith("~");
      const k = raw.replace(/^~/, "").toLowerCase().replace(/ё/g, "е");
      if (k.includes(" ")) { if (q.includes(k)) score += weak ? 1 : 2; continue; }
      if (words.some((w) => hit(w, k))) score += weak ? 1 : 2;
    }
    return { a, score };
  }).filter((x) => x.score >= MIN_SCORE).sort((x, y) => y.score - x.score);
  return scored.slice(0, 3).map((x) => x.a);
}

export function articleBy(doc: string, point: string): Article | undefined {
  return ARTICLES.find((a) => a.doc === doc && a.point === point);
}
