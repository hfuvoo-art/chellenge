const STOP = new Set(["что", "как", "мне", "меня", "это", "если", "или", "для", "когда", "можно", "нужно", "надо", "есть", "был", "была", "по", "на", "не", "и", "в", "с", "а", "я", "у", "ли"]);

function tokens(text: string): string[] {
  return text.toLowerCase().replace(/ё/g, "е").split(/[^a-zа-я0-9]+/).filter((w) => w.length > 2 && !STOP.has(w));
}

/** Простой поиск по ключам: совпадение начала слова с ключом. Возвращает до 3 подходящих пунктов. */
export function searchArticles(query: string): Article[] {
  const words = tokens(query);
  const norm = (k: string) => k.toLowerCase().replace(/ё/g, "е");
  const scored = ARTICLES.map((a) => {
    let score = 0;
    for (const k of a.keywords.map(norm)) {
      if (k.includes(" ")) { if (query.toLowerCase().replace(/ё/g, "е").includes(k)) score += 2; continue; }
      for (const w of words) if (w.startsWith(k) || (k.length >= 5 && k.startsWith(w.slice(0, 5)))) { score += 1; break; }
    }
    return { a, score };
  }).filter((x) => x.score > 0).sort((x, y) => y.score - x.score);
  return scored.slice(0, 3).map((x) => x.a);
}
